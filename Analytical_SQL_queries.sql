-- Q27: Analyze the yearly performance of products by comparing their sales to
--      both the average sales performance of the product and the previous year's sales.   
WITH YEARLY_PRODUCT_SALES AS (
SELECT YEAR(FACT_SALES.ORDER_DATE) AS ORDER_YEAR,  
DIM_PRODUCTS.PRODUCT_NAME AS PRODUCT_NAME,
SUM(FACT_SALES.SALES_AMOUNT) AS CURRENT_SALES
FROM FACT_SALES 
LEFT JOIN DIM_PRODUCTS
ON FACT_SALES.PRODUCT_KEY = DIM_PRODUCTS.PRODUCT_KEY
WHERE ORDER_DATE IS NOT NULL
GROUP BY YEAR(FACT_SALES.ORDER_DATE),
DIM_PRODUCTS.PRODUCT_NAME)
SELECT ORDER_YEAR,
 PRODUCT_NAME,
 CURRENT_SALES,
 AVG(CURRENT_SALES) OVER (PARTITION BY PRODUCT_NAME) AS AVG_SALES,
 CURRENT_SALES - AVG(CURRENT_SALES) OVER (PARTITION BY PRODUCT_NAME) AS DIFF_AVG,
 CASE
      WHEN CURRENT_SALES - AVG(CURRENT_SALES) OVER (PARTITION BY PRODUCT_NAME) > 0 THEN "ABOVE AVG"
       WHEN CURRENT_SALES - AVG(CURRENT_SALES) OVER (PARTITION BY PRODUCT_NAME) < 0 THEN "BELOW AVG"
         ELSE "AVG"
 END AVG_CHANGE,     
 LAG(CURRENT_SALES,1) OVER (PARTITION BY PRODUCT_NAME ORDER BY ORDER_YEAR) AS PREVIUOS_YEAR_SALE,
 CURRENT_SALES - LAG(CURRENT_SALES,1) OVER (PARTITION BY PRODUCT_NAME ORDER BY ORDER_YEAR) AS DIFF_PREVIOUS_SALES,
 CASE
      WHEN CURRENT_SALES - LAG(CURRENT_SALES,1) OVER (PARTITION BY PRODUCT_NAME ORDER BY ORDER_YEAR) > 0 THEN "INCREASE"
       WHEN CURRENT_SALES - LAG(CURRENT_SALES,1) OVER (PARTITION BY PRODUCT_NAME ORDER BY ORDER_YEAR) < 0 THEN "DECREASE"
         ELSE "NO CHANGE"
 END PREVIOUS_YEAR_SALES_CHANGE
 FROM YEARLY_PRODUCT_SALES
 ORDER BY PRODUCT_NAME, ORDER_YEAR;   
 
 
 -- Q28: Which categories contribute the most to overall sales?
 WITH CATEGORY_SALES AS
 (SELECT
 CATEGORY,
 SUM(SALES_AMOUNT) AS TOTAL_SALES
 FROM FACT_SALES 
 LEFT JOIN DIM_PRODUCTS 
 ON FACT_SALES.PRODUCT_KEY = DIM_PRODUCTS.PRODUCT_KEY
 GROUP BY CATEGORY)
SELECT
CATEGORY,
TOTAL_SALES,
SUM(TOTAL_SALES) OVER () OVERALL_SALES,
CONCAT(ROUND((TOTAL_SALES / SUM(TOTAL_SALES) OVER () ) * 100,2), '%') AS PERCENTAGE_OF_TOTAL
FROM CATEGORY_SALES
ORDER BY TOTAL_SALES DESC;


-- Q29: Segment products into cost ranges and 
--      count how many products fall into each segment.
WITH PRODUCT_SEGMENTS AS (
 SELECT 
 PRODUCT_KEY,
 PRODUCT_NAME,
 COST,
 CASE
     WHEN COST < 100 THEN 'BELOW 100'
     WHEN COST BETWEEN 100 AND 500 THEN '100-500'
     WHEN COST BETWEEN 500 AND 1000 THEN '500-1000'
     ELSE 'ABOVE 1000'
END COST_RANGE
 FROM DIM_PRODUCTS)
 SELECT 
 COST_RANGE,
 COUNT(PRODUCT_KEY) AS TOTAL_PRODUCTS
 FROM PRODUCT_SEGMENTS
 GROUP BY COST_RANGE
 ORDER BY TOTAL_PRODUCTS DESC;
 
 
-- Q30: Group customers into three segments based on their spending behavior:
--      VIP: Customers with at least 12 months of history and spending more than €5,000.
--      Regular: Customers with at least 12 months of history but spending €5,000 or less.
--      New: Customers with a lifespan less than 12 months.
--      And find the total number of customers by each group.
WITH CUSTOMER_SPENDING AS (
 SELECT 
 DIM_CUSTOMERS.CUSTOMER_KEY,
 SUM(SALES_AMOUNT) AS TOTAL_SPENDING,
 MIN(ORDER_DATE) AS FIRST_ORDER,
 MAX(ORDER_DATE) AS LAST_ORDER,
 timestampdiff(MONTH, MIN(ORDER_DATE),MAX(ORDER_DATE)) AS LIFESPAN
 FROM FACT_SALES LEFT JOIN DIM_CUSTOMERS 
 ON FACT_SALES.CUSTOMER_KEY = DIM_CUSTOMERS.CUSTOMER_KEY
 GROUP BY DIM_CUSTOMERS.CUSTOMER_KEY )
 SELECT 
 CUSTOMER_SEGMENT,
 COUNT(CUSTOMER_KEY) AS TOTAL_CUSTOMERS
 FROM (
 SELECT CUSTOMER_KEY,
 CASE
     WHEN LIFESPAN >= 12 AND TOTAL_SPENDING > 5000 THEN 'VIP'
     WHEN LIFESPAN >= 12 AND TOTAL_SPENDING <= 5000 THEN 'REGULAR'
     ELSE 'NEW'
 END AS CUSTOMER_SEGMENT    
 FROM CUSTOMER_SPENDING
 ) AS SEGMENTED_CUSTOMERS
 GROUP BY CUSTOMER_SEGMENT
 ORDER BY TOTAL_CUSTOMERS DESC;